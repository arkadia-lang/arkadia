// Package codegen translates Core programs to Go source code.
package codegen

import (
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/verniyyy/arkadia/internal/core"
)

// RuntimeImport is the import path of the runtime inside generated modules.
const RuntimeImport = "arkprog/rt"

// Options controls code generation.
type Options struct {
	Tests bool // generate a test runner instead of calling main
}

type globalKind int

const (
	gFunc globalKind = iota
	gValue
	gDict
	gDictFn
	gForeign
	gOp
)

type globalInfo struct {
	kind   globalKind
	arity  int
	name   string // Go identifier for direct calls / value access
	target string // foreign target
	slots  int
}

type gen struct {
	prog    *core.Program
	globals map[string]*globalInfo
	effIDs  map[string]int
	out     strings.Builder
	tmp     int
	aliases map[string]string
}

// Generate produces the Go source of the main package.
func Generate(p *core.Program, opts Options) ([]byte, error) {
	Optimize(p)
	g := &gen{prog: p, globals: map[string]*globalInfo{}, effIDs: map[string]int{}}
	for i, e := range p.Effects {
		g.effIDs[e.Name] = i
	}
	for _, f := range p.Funcs {
		g.globals[f.Sym] = &globalInfo{kind: gFunc, arity: len(f.Params), name: "f_" + mangle(f.Sym)}
	}
	for _, v := range p.Values {
		g.globals[v.Sym] = &globalInfo{kind: gValue, name: "v_" + mangle(v.Sym)}
	}
	for _, d := range p.Dicts {
		if len(d.Params) == 0 {
			g.globals[d.Sym] = &globalInfo{kind: gDict, name: "d_" + mangle(d.Sym), slots: len(d.Slots)}
		} else {
			g.globals[d.Sym] = &globalInfo{kind: gDictFn, arity: len(d.Params), name: "mk_" + mangle(d.Sym), slots: len(d.Slots)}
		}
	}
	for _, f := range p.Foreigns {
		g.globals[f.Sym] = &globalInfo{kind: gForeign, arity: f.Arity, name: f.Target, target: f.Target}
	}
	for _, o := range p.Ops {
		g.globals[o.Sym] = &globalInfo{kind: gOp, arity: o.Arity, name: "op_" + mangle(o.Sym)}
	}
	g.program(opts)
	src := []byte(g.out.String())
	formatted, err := format.Source(src)
	if err != nil {
		return src, fmt.Errorf("internal error: generated Go code does not parse: %v", err)
	}
	return formatted, nil
}

// mangle turns a symbol into a Go identifier fragment.
func mangle(s string) string {
	var sb strings.Builder
	for _, r := range s {
		switch {
		case r == '.':
			sb.WriteByte('_')
		case r == '$':
			sb.WriteRune('ǂ')
		case r == '_' || r < 128 && (unicode.IsLetter(r) || unicode.IsDigit(r)):
			sb.WriteRune(r)
		case r >= 128 && (unicode.IsLetter(r) || unicode.IsDigit(r)):
			sb.WriteRune(r)
		default:
			fmt.Fprintf(&sb, "ǀ%x", r)
		}
	}
	return sb.String()
}

func local(name string) string { return "l_" + mangle(name) }

func (g *gen) printf(format string, args ...any) { fmt.Fprintf(&g.out, format, args...) }

// closureName is the Go variable holding a global function as a value.
func closureName(sym string) string { return "c_" + mangle(sym) }

func fnType(n int) string {
	if n <= 4 {
		return "rt.Fn" + strconv.Itoa(n)
	}
	return ""
}

func params(n int, prefix string) string {
	var ps []string
	for i := 0; i < n; i++ {
		ps = append(ps, fmt.Sprintf("%s%d", prefix, i))
	}
	if n == 0 {
		return ""
	}
	return strings.Join(ps, ", ") + " rt.Value"
}

func argList(n int, prefix string) string {
	var ps []string
	for i := 0; i < n; i++ {
		ps = append(ps, fmt.Sprintf("%s%d", prefix, i))
	}
	return strings.Join(ps, ", ")
}

// closureOf wraps a Go function of arity n as an Arkadia function value.
func closureOf(fn string, n int) string {
	if n <= 4 {
		return fmt.Sprintf("rt.Fn%d(%s)", n, fn)
	}
	var idx []string
	for i := 0; i < n; i++ {
		idx = append(idx, fmt.Sprintf("a[%d]", i))
	}
	return fmt.Sprintf("&rt.FnN{N: %d, F: func(a []rt.Value) rt.Value { return %s(%s) }}", n, fn, strings.Join(idx, ", "))
}

func (g *gen) program(opts Options) {
	g.printf("// Code generated by the Arkadia compiler. DO NOT EDIT.\n\npackage main\n\n")
	g.printf("import rt %q\n\n", RuntimeImport)
	g.printf("var _ = rt.Unit\n\n")

	// effect ops
	for _, o := range g.prog.Ops {
		info := g.globals[o.Sym]
		g.printf("func %s(%s) rt.Value { return rt.Perform(%d, %d, []rt.Value{%s}) }\n\n", info.name, params(o.Arity, "a"), g.effIDs[o.Eff], o.Index, argList(o.Arity, "a"))
	}
	// functions
	for _, f := range g.prog.Funcs {
		g.function(f)
	}
	// dictionary constructors
	for _, d := range g.prog.Dicts {
		info := g.globals[d.Sym]
		if info.kind == gDict {
			g.printf("var %s = rt.NewDict(%d)\n\n", info.name, len(d.Slots))
			continue
		}
		c := g.newCtx()
		for i, p := range d.Params {
			c.line("%s := a%d", local(p), i)
			c.line("_ = %s", local(p))
		}
		c.line("%s := rt.NewDict(%d)", local("self"), len(d.Slots))
		for i, s := range d.Slots {
			v := c.expr(s)
			c.line("%s.S[%d] = %s", local("self"), i, v.code)
		}
		c.line("return %s", local("self"))
		g.printf("func %s(%s) rt.Value {\n%s}\n\n", info.name, params(len(d.Params), "a"), c.body.String())
	}
	// closure values and constants
	var syms []string
	for sym, info := range g.globals {
		switch info.kind {
		case gFunc, gDictFn, gOp:
			syms = append(syms, sym)
		case gForeign:
			if info.arity > 0 {
				syms = append(syms, sym)
			}
		case gValue:
			g.printf("var %s rt.Value\n", info.name)
		}
	}
	sort.Strings(syms)
	for _, sym := range syms {
		g.printf("var %s rt.Value\n", closureName(sym))
	}
	g.printf("\nfunc init() {\n")
	for _, sym := range syms {
		info := g.globals[sym]
		g.printf("\t%s = %s\n", closureName(sym), closureOf(info.name, info.arity))
	}
	// effect names for diagnostics
	g.printf("\trt.EffectNames = []string{")
	for _, e := range g.prog.Effects {
		g.printf("%q, ", shortName(e.Name))
	}
	g.printf("}\n\trt.OpNames = [][]string{")
	for _, e := range g.prog.Effects {
		g.printf("{")
		for _, o := range e.Ops {
			g.printf("%q, ", o)
		}
		g.printf("}, ")
	}
	g.printf("}\n")
	// dictionaries and values in dependency order
	for _, item := range g.initOrder() {
		switch it := item.(type) {
		case *core.Dict:
			info := g.globals[it.Sym]
			c := g.newCtx()
			c.line("%s := %s", local("self"), info.name)
			for i, s := range it.Slots {
				v := c.expr(s)
				c.line("%s.S[%d] = %s", local("self"), i, v.code)
			}
			g.printf("\t{\n%s\t}\n", c.body.String())
		case *core.Value:
			info := g.globals[it.Sym]
			c := g.newCtx()
			c.stmt(it.Body, dest{kind: dRet})
			g.printf("\t%s = func() rt.Value {\n%s\t}()\n", info.name, c.body.String())
		}
	}
	g.printf("}\n\n")

	if opts.Tests {
		failID := -1
		if id, ok := g.effIDs[g.prog.FailEff]; ok {
			failID = id
		}
		g.printf("func main() {\n\trt.Main(func() {\n\t\trt.RunTests(%d, []rt.TestCase{\n", failID)
		for _, t := range g.prog.Tests {
			info := g.globals[t.Sym]
			mod := t.Sym[:strings.LastIndex(t.Sym, ".")]
			g.printf("\t\t\t{Module: %q, Name: %q, Run: func() { %s(rt.Unit) }},\n", mod, t.Name, info.name)
		}
		g.printf("\t\t})\n\t})\n}\n")
		return
	}
	if g.prog.Main != "" {
		info := g.globals[g.prog.Main]
		call := ""
		switch info.kind {
		case gFunc:
			call = fmt.Sprintf("%s(rt.Unit)", info.name)
		default:
			call = fmt.Sprintf("rt.Apply1(%s, rt.Unit)", info.name)
		}
		g.printf("func main() {\n\trt.Main(func() { %s })\n}\n", call)
	}
}

func shortName(n string) string {
	if i := strings.LastIndex(n, "."); i >= 0 {
		return n[i+1:]
	}
	return n
}

// initOrder sorts dictionaries and values so that each is initialized after
// the values and dictionaries it (transitively) uses.
func (g *gen) initOrder() []any {
	funcs := map[string]*core.Func{}
	for _, f := range g.prog.Funcs {
		funcs[f.Sym] = f
	}
	items := map[string]any{}
	var order []string
	for _, d := range g.prog.Dicts {
		if len(d.Params) == 0 {
			items[d.Sym] = d
			order = append(order, d.Sym)
		}
	}
	for _, v := range g.prog.Values {
		items[v.Sym] = v
		order = append(order, v.Sym)
	}
	dictFns := map[string]*core.Dict{}
	for _, d := range g.prog.Dicts {
		if len(d.Params) > 0 {
			dictFns[d.Sym] = d
		}
	}
	// direct references of each global
	refsOf := func(es ...core.Expr) []string {
		var out []string
		for _, e := range es {
			core.Walk(e, func(x core.Expr) bool {
				if gl, ok := x.(*core.Global); ok {
					out = append(out, gl.Sym)
				}
				return true
			})
		}
		return out
	}
	// items reachable through functions
	reach := map[string][]string{}
	var deps func(sym string, seen map[string]bool, acc *[]string)
	deps = func(sym string, seen map[string]bool, acc *[]string) {
		if seen[sym] {
			return
		}
		seen[sym] = true
		var refs []string
		if f, ok := funcs[sym]; ok {
			refs = refsOf(f.Body)
		} else if d, ok := dictFns[sym]; ok {
			refs = refsOf(d.Slots...)
		} else if it, ok := items[sym]; ok {
			*acc = append(*acc, sym)
			_ = it
			return
		}
		for _, r := range refs {
			deps(r, seen, acc)
		}
	}
	for sym, it := range items {
		var refs []string
		switch it := it.(type) {
		case *core.Dict:
			refs = refsOf(it.Slots...)
		case *core.Value:
			refs = refsOf(it.Body)
		}
		seen := map[string]bool{sym: true}
		var acc []string
		for _, r := range refs {
			deps(r, seen, &acc)
		}
		reach[sym] = acc
	}
	state := map[string]int{}
	var out []any
	var visit func(sym string)
	visit = func(sym string) {
		if state[sym] != 0 {
			return
		}
		state[sym] = 1
		for _, d := range reach[sym] {
			visit(d)
		}
		state[sym] = 2
		out = append(out, items[sym])
	}
	for _, sym := range order {
		visit(sym)
	}
	return out
}

// ---------------------------------------------------------------- functions

func (g *gen) function(f *core.Func) {
	info := g.globals[f.Sym]
	c := g.newCtx()
	c.self = &selfInfo{global: f.Sym, arity: len(f.Params)}
	c.indent = 2
	for i, p := range f.Params {
		c.line("%s := a%d", local(p), i)
		c.line("_ = %s", local(p))
	}
	c.stmt(f.Body, dest{kind: dRet})
	if c.self.used {
		g.printf("func %s(%s) rt.Value {\n\tfor {\n%s\t}\n}\n\n", info.name, params(len(f.Params), "a"), c.body.String())
	} else {
		g.printf("func %s(%s) rt.Value {\n%s}\n\n", info.name, params(len(f.Params), "a"), dedent(c.body.String()))
	}
}

func dedent(s string) string {
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		lines[i] = strings.TrimPrefix(l, "\t")
	}
	return strings.Join(lines, "\n")
}
